/** Approximate blackbody colour for a stellar temperature (for visuals only). */
export function starColor(tempK: number): string {
  if (tempK >= 10000) return '#a9c8ff';
  if (tempK >= 7500) return '#cfdcff';
  if (tempK >= 6000) return '#fff4e8';
  if (tempK >= 5200) return '#ffe2a8';
  if (tempK >= 3700) return '#ffbe73';
  return '#ff9a5a';
}
